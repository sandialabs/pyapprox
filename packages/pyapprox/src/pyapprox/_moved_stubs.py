"""Type stubs at the old paths of moved modules.

mypy cannot see :mod:`pyapprox._moved`'s runtime finder, so each module
under a moved prefix gets a generated ``.pyi`` at its old path that binds
every module-level name of the new module, private ones included (tests
import private helpers), and exports exactly what the new module exports,
so an old path types as the new one does. Names are read from the source
with :mod:`ast`; nothing is imported.

Run ``python -m pyapprox._moved_stubs`` to write the stubs for
:data:`pyapprox._moved.MOVED` and delete stale ones, or with ``--check``
to report differences without writing.
"""

import ast
import sys
from pathlib import Path
from typing import Mapping, Optional

HEADER = (
    "# Generated by pyapprox._moved_stubs from pyapprox._moved.MOVED; do not edit.\n"
)

LINT_EXEMPT = "# ruff: noqa\n"
"""Second line of every stub. A stub binds names it does not export (its
imports and private names), one line each without wrapping, so it cannot
satisfy ruff's unused-import, line-length and import-order rules. It is
not part of :data:`HEADER`, which identifies generated stubs."""


def _stub_body(module: str, package: str, source: str, filename: str) -> str:
    """The stub for the module ``module`` with source ``source``.

    One line per module-level name, including names bound under top-level
    ``if``/``try`` blocks; the first binding of a name wins. A name the
    module defines comes from ``module``; a name it imports comes from
    where it was imported (relative imports resolved against
    ``package``), since under ``--strict`` a module does not export what
    it merely imports and ``from module import name`` would not resolve.

    The stub's ``__all__`` lists what the module exports and nothing
    more: the names it defines, those it re-exports as ``name as name``,
    and those in its own ``__all__``. An old path then types exactly as
    the new one does: a name only imported by the new module is
    unexported through both.
    """
    lines: dict[str, str] = {}
    exported: list[str] = []

    def define(name: str) -> None:
        lines.setdefault(name, f"from {module} import {name} as {name}\n")
        exported.append(name)

    def declared(value: Optional[ast.expr]) -> None:
        if isinstance(value, (ast.List, ast.Tuple)):
            exported.extend(
                e.value
                for e in value.elts
                if isinstance(e, ast.Constant) and isinstance(e.value, str)
            )

    def bind(target: ast.expr, value: Optional[ast.expr] = None) -> None:
        if isinstance(target, ast.Name) and target.id == "__all__":
            declared(value)
        elif isinstance(target, ast.Name):
            define(target.id)
        elif isinstance(target, (ast.Tuple, ast.List)):
            for element in target.elts:
                bind(element)

    def imported(name: str, line: str, explicit: bool) -> None:
        lines.setdefault(name, line)
        if explicit:
            exported.append(name)

    def source_of(node: ast.ImportFrom) -> str:
        if node.level == 0:
            return node.module or ""
        base = package.split(".")[: len(package.split(".")) - node.level + 1]
        return ".".join(base + ([node.module] if node.module else []))

    def visit(body: list[ast.stmt]) -> None:
        for node in body:
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                define(node.name)
            elif isinstance(node, ast.Assign):
                for target in node.targets:
                    bind(target, node.value)
            elif isinstance(node, (ast.AnnAssign, ast.AugAssign)):
                bind(node.target, node.value)
            elif isinstance(node, ast.ImportFrom):
                origin = source_of(node)
                for alias in node.names:
                    if alias.name == "*":
                        raise ValueError(
                            f"{filename}: 'import *' binds names a stub cannot list"
                        )
                    name = alias.asname or alias.name
                    # Never ``name as name``: in a stub that exports the
                    # name whatever ``__all__`` says.
                    rename = f" as {name}" if name != alias.name else ""
                    line = f"from {origin} import {alias.name}{rename}\n"
                    imported(name, line, alias.asname == alias.name)
            elif isinstance(node, ast.Import):
                for alias in node.names:
                    # ``import a.b`` binds ``a``; ``import a.b as c`` binds c.
                    name = alias.asname or alias.name.split(".")[0]
                    rename = f" as {name}" if alias.asname else ""
                    line = f"import {alias.name}{rename}\n"
                    imported(name, line, alias.asname == alias.name)
            elif isinstance(node, ast.If):
                visit(node.body)
                visit(node.orelse)
            elif isinstance(node, ast.Try):
                visit(node.body)
                for handler in node.handlers:
                    visit(handler.body)
                visit(node.orelse)
                visit(node.finalbody)

    visit(ast.parse(source, filename).body)
    names = [n for n in dict.fromkeys(exported) if n in lines]
    return "".join(lines.values()) + f"__all__ = {names!r}\n"


def expected_stubs(table: Mapping[str, str], root: Path) -> dict[Path, str]:
    """Every stub ``table`` calls for under the source root ``root``."""
    stubs: dict[Path, str] = {}
    for old, new in table.items():
        old_path, new_path = (
            root.joinpath(*old.split(".")),
            root.joinpath(*new.split(".")),
        )
        if new_path.with_suffix(".py").is_file():
            sources = {new_path.with_suffix(".py"): old_path.with_suffix(".pyi")}
        elif new_path.is_dir():
            sources = {
                py: old_path / py.relative_to(new_path).with_suffix(".pyi")
                for py in sorted(new_path.rglob("*.py"))
            }
        else:
            raise FileNotFoundError(
                f"{new} (the new home of {old}) is not under {root}"
            )
        for py, pyi in sources.items():
            parts = py.relative_to(root).with_suffix("").parts
            is_package = parts[-1] == "__init__"
            module = ".".join(parts[:-1] if is_package else parts)
            # Relative imports resolve against the package containing the
            # module: the module itself when it is an __init__.
            package = module if is_package else ".".join(parts[:-1])
            stubs[pyi] = (
                HEADER
                + LINT_EXEMPT
                + _stub_body(module, package, py.read_text(), str(py))
            )
    return stubs


def _generated(root: Path) -> list[Path]:
    return [p for p in sorted(root.rglob("*.pyi")) if p.read_text().startswith(HEADER)]


def check(table: Mapping[str, str], root: Path) -> list[str]:
    """Differences between the stubs on disk and those ``table`` calls
    for: missing, edited or stale. Empty when in sync."""
    expected = expected_stubs(table, root)
    problems = [
        f"{'missing' if not p.exists() else 'out of date'}: {p}"
        for p, text in expected.items()
        if not p.exists() or p.read_text() != text
    ]
    problems += [f"stale: {p}" for p in _generated(root) if p not in expected]
    return problems


def write(table: Mapping[str, str], root: Path) -> None:
    """Write the stubs ``table`` calls for and delete stale generated ones."""
    expected = expected_stubs(table, root)
    for path in _generated(root):
        if path not in expected:
            path.unlink()
    for path, text in expected.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)


def main(argv: list[str]) -> int:
    from pyapprox._moved import MOVED

    root = Path(__file__).resolve().parent.parent
    if "--check" in argv:
        problems = check(MOVED, root)
        print("\n".join(problems) or "stubs in sync")
        return 1 if problems else 0
    write(MOVED, root)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
